"""Схема данных пересобранных деревьев развития.

Технология описывается кодом (устойчивый идентификатор, по нему строятся
связи), названием, категорией, коротким описанием, исторической справкой и
списком кодов технологий, без которых она невозможна.

Эпоха у технологии не хранится в самой записи: она задаётся тем, в каком
списке эпохи технология лежит. Так исключены расхождения между полем и
фактическим размещением.
"""

from collections import namedtuple

Tech = namedtuple("Tech", "code name cat desc note pre")


def T(code, name, cat, desc, note, pre=()):
    """Технология. pre — коды технологий-оснований (может быть пустым)."""
    return Tech(code, name, cat, desc, note, tuple(pre))


