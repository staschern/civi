-- =====================================================================
--  Civi · миграция 0002
--  Базовая стоимость версии: от неё считаются средние по столбцам.
--
--  Раньше отправная точка (130) была зашита в коде. Теперь она хранится
--  у версии, и её можно менять из интерфейса: среднее любого столбца
--  равно cost_base × 1.5^номер_столбца, поэтому правка среднего в одном
--  столбце пересчитывает средние во всех остальных.
--
--  Накатывается поверх существующей базы, данные не трогает.
-- =====================================================================

SET NAMES utf8mb4;

ALTER TABLE tree_versions
  ADD COLUMN cost_base INT UNSIGNED NOT NULL DEFAULT 130
    COMMENT 'средняя стоимость технологии первого столбца'
    AFTER generator_version;
